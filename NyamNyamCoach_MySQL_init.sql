DROP DATABASE IF EXISTS `NyamNyamCoach`;

CREATE DATABASE `NyamNyamCoach` DEFAULT CHARACTER SET utf8mb4;

USE NyamNyamCoach;

CREATE TABLE IF NOT EXISTS `Diet` (
    `DietID` VARCHAR(255) NOT NULL,
    `DietMenu` VARCHAR(255),
    `DietKcal` INTEGER,
    `DietCarbs` DOUBLE,
    `DietProtein` DOUBLE,
    `DietFat` DOUBLE,
    PRIMARY KEY(`DietID`)
);


CREATE TABLE IF NOT EXISTS `User` (
    `UUID` INTEGER NOT NULL,
    `ID` VARCHAR(255),
    `PW` VARCHAR(255),
    `UserName` VARCHAR(255),
    `UserHeight` INTEGER,
    `UserWeight` DOUBLE,
    PRIMARY KEY(`UUID`)
);


CREATE TABLE IF NOT EXISTS `DietLog` (
    `LogID` INTEGER NOT NULL AUTO_INCREMENT,
    `DietID` VARCHAR(255) NOT NULL,
    `UUID` INTEGER NOT NULL,
    `Date` DATE,
    `TimeStamp` TIME,
    PRIMARY KEY(`LogID`),
    FOREIGN KEY(`DietID`) REFERENCES `Diet`(`DietID`),
    FOREIGN KEY(`UUID`) REFERENCES `User`(`UUID`)
);


